export const clone = value => structuredClone(value);
export const uid = () => crypto.randomUUID();
export function normalize(site = {}) {
  const saved = site.priceRate || {};
  if ([3, 4].includes(saved.version) && Array.isArray(saved.sections)) {
    const model=clone(saved);
    if(model.version===3)for(const section of model.sections)for(const block of section.blocks){if(['gallery','video','slideshow'].includes(block.kind)&&block.fit!=='natural')block.fit='contain';}
    model.version=4;
    return model;
  }
  const sections = clone(DEFAULT_SECTIONS).filter(section => section.name !== "Scale");
  for (const section of sections) {
    if (saved.texts?.[section.legacyName] !== undefined) section.name = saved.texts[section.legacyName];
    for (const block of section.blocks) {
      if (block.kind === 'gallery' && saved.galleries?.[block.legacyGallery]) block.images = clone(saved.galleries[block.legacyGallery]);
      if (block.kind === 'table') for (const row of block.rows) for (const cell of row) cell.text = saved.texts?.[cell.legacyKey] ?? cell.text;
      if (block.kind === 'text') block.text = block.text.split('\n').map((line, i) => saved.texts?.[block.legacyLines[i]] ?? line).join('\n');
    }
  }
  for (const section of saved.sections || []) sections.push({id: section.id || uid(), name: section.name || '', blocks: [{id: uid(), kind: 'text', text: section.description || ''}, {id: uid(), kind: 'gallery', perPage: 3, images: clone(section.images || [])}]});
  for(const section of sections)for(const block of section.blocks){if(block.kind==='gallery')block.fit='contain';}
  return {version: 4, title: 'Price rate', sections};
}
export function el(tag, className, text) {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text !== undefined) node.textContent = text;
  return node;
}
export function button(text, action, label = text) {
  const node = el('button', '', text);
  node.type = 'button'; node.setAttribute('aria-label', label); node.onclick = action;
  return node;
}
